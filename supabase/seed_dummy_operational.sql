CREATE TEMP TABLE tmp_dummy_order_items AS
SELECT
  p.i,
  p.id AS order_id,
  m.id AS menu_item_id,
  m.name,
  (
    m.price
    + CASE WHEN item_seq = 1 AND p.i % 3 = 0 THEN 10 ELSE 0 END
    + CASE WHEN item_seq = 2 AND p.i % 5 = 0 THEN 15 ELSE 0 END
  )::numeric(10, 2) AS price,
  CASE WHEN item_seq = 1 AND p.i % 6 = 0 THEN 2 ELSE 1 END AS quantity,
  jsonb_build_array(
    jsonb_build_object(
      'group', 'size',
      'label', CASE WHEN p.i % 3 = 0 THEN 'Large 22oz' ELSE 'Medium 16oz' END,
      'price_modifier', CASE WHEN p.i % 3 = 0 THEN 10 ELSE 0 END
    ),
    jsonb_build_object(
      'group', 'sugar_level',
      'label', CASE WHEN p.i % 4 = 0 THEN 'Less Sweet' ELSE 'Normal' END,
      'price_modifier', 0
    )
  ) AS variants,
  CASE WHEN p.i % 10 = 0 AND item_seq = 1 THEN 'Demo customization note.' ELSE NULL END AS notes
FROM tmp_dummy_order_plan p
JOIN LATERAL generate_series(1, 1 + (p.i % 3)) AS item_seq ON true
JOIN tmp_dummy_menu m
  ON m.rn = (((p.i * 7) + (item_seq * 11)) % (SELECT max(menu_count) FROM tmp_dummy_menu)) + 1;

