UPDATE public.profiles p
SET
  points = COALESCE(stats.points_balance, 0),
  total_orders = COALESCE(stats.total_orders, 0),
  total_spent = COALESCE(stats.total_spent, 0),
  last_order_at = stats.last_order_at,
  loyalty_tier = CASE
    WHEN COALESCE(stats.points_balance, 0) >= 500 THEN 'Gold'
    WHEN COALESCE(stats.points_balance, 0) >= 200 THEN 'Silver'
    ELSE 'Bronze'
  END,
  favorite_items = COALESCE(stats.favorite_items, '{}'::uuid[]),
  updated_at = now()
FROM (
  SELECT
    o.customer_id,
    GREATEST(SUM(o.points_earned) - SUM(o.points_redeemed), 0)::int AS points_balance,
    COUNT(*) FILTER (WHERE o.payment_status = 'paid')::int AS total_orders,
    SUM(o.total) FILTER (WHERE o.payment_status = 'paid')::numeric(10, 2) AS total_spent,
    MAX(o.created_at) AS last_order_at,
    ARRAY(
      SELECT oi.menu_item_id
      FROM public.order_items oi
      JOIN public.orders oo ON oo.id = oi.order_id
      WHERE oo.customer_id = o.customer_id
        AND oi.menu_item_id IS NOT NULL
      GROUP BY oi.menu_item_id
      ORDER BY COUNT(*) DESC
      LIMIT 3
    ) AS favorite_items
  FROM public.orders o
  WHERE o.order_number LIKE 'DUMMY-%'
    AND o.customer_id IS NOT NULL
  GROUP BY o.customer_id
) stats
WHERE p.id = stats.customer_id;

