-- CafeOS local dummy operational data
-- Creates demo users, 100 orders, order items, status history,
-- pickup tokens, guest receipts, saved addresses, voucher claims,
-- notifications, shifts, clock entries, and void logs.
--
-- This seed intentionally does NOT modify menu/catalog or raw
-- ingredient tables. It only reads menu_items and vouchers.
-- Safe to re-run: it deletes and recreates only records with
-- DUMMY-* order numbers and demo.*@cafeos.local users.
-- ============================================================

BEGIN;

CREATE OR REPLACE FUNCTION pg_temp.cafeos_dummy_uuid(seed text)
RETURNS uuid
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT (
    substr(md5(seed), 1, 8) || '-' ||
    substr(md5(seed), 9, 4) || '-' ||
    '4' || substr(md5(seed), 14, 3) || '-' ||
    'a' || substr(md5(seed), 18, 3) || '-' ||
    substr(md5(seed), 21, 12)
  )::uuid;
$$;

