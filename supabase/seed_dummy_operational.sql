INSERT INTO public.order_status_history (
  order_id,
  previous_status,
  new_status,
  changed_by,
  notes,
  created_at
)
SELECT
  o.id,
  h.previous_status,
  h.new_status,
  o.staff_id,
  'Dummy workflow status history',
  o.created_at + (h.minutes_after * interval '1 minute')
FROM tmp_dummy_order_plan o
JOIN LATERAL (
  VALUES
    (1, NULL::public.order_status, 'pending'::public.order_status, 0),
    (2, 'pending'::public.order_status, 'confirmed'::public.order_status, 8),
    (3, 'confirmed'::public.order_status, 'preparing'::public.order_status, 18),
    (4, 'preparing'::public.order_status, 'ready'::public.order_status, 35),
    (5, 'ready'::public.order_status, 'completed'::public.order_status, 60)
) AS h(step_no, previous_status, new_status, minutes_after)
  ON o.status <> 'cancelled'
WHERE h.step_no <= CASE o.status
  WHEN 'pending' THEN 1
  WHEN 'confirmed' THEN 2
  WHEN 'preparing' THEN 3
  WHEN 'ready' THEN 4
  WHEN 'completed' THEN 5
  ELSE 1
END;

